// Turns files into C arrays: embed out.h name=path [name=path...]. Build tool only.
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv) {
  if (argc < 3) return fprintf(stderr, "usage: embed out.h name=path...\n"), 2;
  FILE *o = fopen(argv[1], "w");
  if (!o) return perror(argv[1]), 1;
  fprintf(o, "// Generated by tools/embed.c\n#pragma once\n");
  for (int i = 2; i < argc; i++) {
    char *eq = strchr(argv[i], '=');
    if (!eq) return fprintf(stderr, "bad argument %s\n", argv[i]), 2;
    *eq = 0;
    FILE *f = fopen(eq + 1, "rb");
    if (!f) return perror(eq + 1), 1;
    fprintf(o, "static const unsigned char %s[] = {", argv[i]);
    int c;
    long n = 0;
    while ((c = fgetc(f)) != EOF) fprintf(o, "%s%d,", n++ % 32 ? "" : "\n", c);
    fprintf(o, "0};\n");
    fclose(f);
  }
  fclose(o);
  return 0;
}
